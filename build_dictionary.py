"""Build normalized, length-specific runtime dictionaries from pinned sources."""

from __future__ import annotations

import re
from pathlib import Path


ROOT = Path(__file__).resolve().parent
DICTIONARY = ROOT / "dictionaries" / "en-US"
SOURCE = DICTIONARY / "source"
ALLOWED_SOURCE = SOURCE / "en_US-large.txt"
ANSWER_SOURCE = SOURCE / "en_US-size35.txt"
BLOCKLIST_SOURCE = SOURCE / "LDNOOBW-en.txt"
BLOCKLIST_EXTRA = SOURCE / "blocklist-extra.txt"
WORD = re.compile(r"[A-Za-z]+\Z", re.ASCII)
WORD_LENGTHS = (5,)


def _entries(path: Path, pattern: re.Pattern[str]) -> set[str]:
    entries: set[str] = set()
    try:
        with path.open("r", encoding="utf-8") as source_file:
            for line in source_file:
                candidate = line.strip()
                if pattern.fullmatch(candidate):
                    entries.add(candidate.lower())
    except (OSError, UnicodeError) as error:
        raise RuntimeError(f"Required dictionary source {path} is unavailable: {error}") from error
    return entries


def _write_words(path: Path, words: set[str], header: str) -> None:
    if not words:
        raise RuntimeError(f"Refusing to write an empty dictionary: {path}")
    path.write_text(header + "\n" + "\n".join(sorted(words)) + "\n", encoding="utf-8", newline="\n")


def build_dictionary() -> dict[str, int]:
    """Filter and deduplicate sources; answers must also be legal guesses."""
    for required in (ALLOWED_SOURCE, ANSWER_SOURCE, BLOCKLIST_SOURCE, BLOCKLIST_EXTRA):
        if not required.is_file():
            raise RuntimeError(f"Required dictionary source file is missing: {required}")

    blocked = _entries(BLOCKLIST_SOURCE, WORD)
    blocked.update(_entries(BLOCKLIST_EXTRA, WORD))
    allowed_source = _entries(ALLOWED_SOURCE, WORD)
    answer_source = _entries(ANSWER_SOURCE, WORD)

    _write_words(
        DICTIONARY / "blocked_words.txt",
        blocked,
        "# Exact en-US terms excluded from every configured game-word length.",
    )
    counts = {"blocked_words": len(blocked)}
    for word_length in WORD_LENGTHS:
        allowed = {word for word in allowed_source if len(word) == word_length} - blocked
        answers = {word for word in answer_source if len(word) == word_length} - blocked

        # Some ESDB size-35 entries can be absent from the size-70 Hunspell export.
        # Keep a single authoritative validity rule: an answer must also be guessable.
        answers.intersection_update(allowed)
        if not answers:
            raise RuntimeError(
                f"No {word_length}-letter answers remain after Allowed Guesses validation"
            )

        _write_words(
            DICTIONARY / f"allowed_guesses_{word_length}.txt",
            allowed,
            f"# Generated by build_dictionary.py from pinned en_US-large source ({word_length} letters).",
        )
        _write_words(
            DICTIONARY / f"answer_words_{word_length}.txt",
            answers,
            f"# Generated by build_dictionary.py from pinned ESDB size-35 list ({word_length} letters).",
        )
        counts[f"allowed_guesses_{word_length}"] = len(allowed)
        counts[f"answer_words_{word_length}"] = len(answers)
        counts[f"blocked_words_{word_length}"] = sum(
            len(word) == word_length for word in blocked
        )
    return counts


if __name__ == "__main__":
    print(build_dictionary())
